public class Operators
{
 public static void main(String[] args)
 {
 int a = 7;
 int b = 2;
 float a1 = 7f;
 float b1 = 2f;
 System.out.println(a+b);
 System.out.println(a-b);
 System.out.println(a*b);
 System.out.println(a/b);
 System.out.println(a1/b1);
 System.out.println(a%b);
 System.out.println(a < b);
 System.out.println(a <= b);
 System.out.println(a == b);
 System.out.println(a != b);
 System.out.println(a > b);
 System.out.println(a >= b);
 System.out.println(a > 5 && b < 5);
 System.out.println(a < 5 || b < 5);
 System.out.println(!(a == b));
 }
}
